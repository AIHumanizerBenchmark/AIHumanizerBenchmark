// Frozen placeholder-selection algorithm for the commit-reveal scheme.
//
// PLAIN JAVASCRIPT ON PURPOSE. This exact file ships in the public cycle bundle
// and the runner imports it, so there is a single implementation. If the runner
// used a TypeScript copy and we published a separate JS one, the two could
// drift and the published algorithm would stop being the one that ran.
//
// Depends only on node:crypto so an auditor can run it with no install:
//
//   node -e "import('./select-placeholders.js').then(m => console.log(
//     m.selectPlaceholders(nonce, templates, banks, count, models)))"
//
// Determinism contract: given the same (nonce, templates, banks, count, models)
// this returns byte-identical output on any machine and any Node version.
// Nothing here may use Math.random, Date, object key order or locale-sensitive
// comparison.

import { createHash } from "node:crypto";

/**
 * Deterministic 32-bit value from (nonce, label, counter).
 * Domain-separated by label so two placeholders never share a draw sequence.
 */
function u32(nonce, label, counter) {
  const digest = createHash("sha256").update(`${nonce}:${label}:${counter}`).digest("hex");
  return parseInt(digest.slice(0, 8), 16);
}

/**
 * Fisher-Yates shuffle driven entirely by the nonce.
 *
 * Shuffling the whole bank up front, then drawing successive entries, is what
 * keeps values from repeating: a template used three times in a cycle gets
 * three different values rather than three independent draws that might collide.
 */
function shuffleBank(nonce, label, bank) {
  const out = bank.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = u32(nonce, label, i) % (i + 1);
    const tmp = out[i];
    out[i] = out[j];
    out[j] = tmp;
  }
  return out;
}

/**
 * Put the generator roster in the order models are dealt out.
 *
 * The nonce shuffles the providers, and separately shuffles the models within
 * each provider. The result interleaves them — first model of each provider,
 * then the second of each, and so on — so that any run of consecutive entries
 * as long as the provider list spans every provider.
 *
 * Shuffle labels contain a slash, which no [PLACEHOLDER] name can, so these
 * draws never share a sequence with a value bank.
 *
 * @param {string} nonce
 * @param {{provider: string, model: string}[]} models
 * @returns {string[]} model ids
 */
function orderModels(nonce, models) {
  const providers = [];
  const byProvider = Object.create(null);
  const seen = Object.create(null);
  for (const entry of models) {
    if (!entry || !entry.provider || !entry.model) {
      throw new Error("selectPlaceholders: each model needs a provider and a model id");
    }
    if (seen[entry.model]) throw new Error(`selectPlaceholders: duplicate model ${entry.model}`);
    seen[entry.model] = true;
    if (!byProvider[entry.provider]) {
      byProvider[entry.provider] = [];
      providers.push(entry.provider);
    }
    byProvider[entry.provider].push(entry.model);
  }

  const queues = shuffleBank(nonce, "models/providers", providers).map((provider) =>
    shuffleBank(nonce, `models/${provider}`, byProvider[provider]),
  );
  const order = [];
  for (let k = 0; order.length < models.length; k++) {
    for (const queue of queues) {
      if (k < queue.length) order.push(queue[k]);
    }
  }
  return order;
}

/**
 * Resolve `count` prompts from the templates and value banks.
 *
 * Templates are assigned round-robin — even coverage across categories is a
 * property we want fixed, not randomised. The nonce decides only WHICH bank
 * value each slot receives, which is the part that could otherwise be steered
 * toward prompts a tool handles well.
 *
 * When a generator roster is given, each prompt is also assigned the model
 * that writes its source text. The nonce fixes the order of the roster (see
 * orderModels); the walk through it is fixed: a template starts at its own
 * position in that order and steps back one model per round. So a template
 * never repeats a model until it has had all of them, its successive texts
 * come from different providers, and whenever `count` is a multiple of the
 * roster size and either the template count or the template count plus one is
 * too, every model writes exactly the same number of texts.
 *
 * @param {string} nonce hex-encoded 32-byte nonce, revealed at cycle close
 * @param {{slug: string, category: string, prompt_text: string}[]} templates
 * @param {Record<string, string[]>} banks
 * @param {number} count
 * @param {{provider: string, model: string}[]} [models] generator roster, as
 *   committed in commit.json. Omitted for cycles generated by a single model.
 */
export function selectPlaceholders(nonce, templates, banks, count, models) {
  if (!nonce) throw new Error("selectPlaceholders: nonce is required");
  if (!templates || templates.length === 0) throw new Error("selectPlaceholders: no templates");

  const modelOrder = models && models.length > 0 ? orderModels(nonce, models) : null;

  const shuffles = Object.create(null);
  const drawn = Object.create(null);
  const selected = [];

  for (let i = 0; i < count; i++) {
    const template = templates[i % templates.length];
    const match = template.prompt_text.match(/\[([A-Z]+)\]/);
    const placeholder = match ? match[1] : "";
    let value = "";

    if (placeholder) {
      if (!shuffles[placeholder]) {
        shuffles[placeholder] = shuffleBank(nonce, placeholder, banks[placeholder] || []);
        drawn[placeholder] = 0;
      }
      const bank = shuffles[placeholder];
      if (bank.length === 0) throw new Error(`selectPlaceholders: empty bank for ${placeholder}`);
      value = bank[drawn[placeholder] % bank.length];
      drawn[placeholder] += 1;
    }

    const pick = {
      index: i,
      templateSlug: template.slug,
      category: template.category,
      placeholder,
      value,
      prompt: match ? template.prompt_text.replace(match[0], value) : template.prompt_text,
    };
    if (modelOrder) {
      const size = modelOrder.length;
      const round = Math.floor(i / templates.length);
      const position = (i % templates.length) - round;
      pick.model = modelOrder[((position % size) + size) % size];
    }
    selected.push(pick);
  }

  return selected;
}

/** sha256 of the nonce — this is what gets published at cycle open. */
export function commitHash(nonce) {
  return createHash("sha256").update(nonce).digest("hex");
}
